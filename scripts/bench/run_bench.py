#!/usr/bin/env python3
"""Run TokenLIKE and both baselines over a pattern list; record reproducible results.

    python scripts/bench/run_bench.py patterns/core.txt --runs 5 --out results/final.json

Pattern files use Person B's format (tab-separated, '#' comments):

    name<TAB>column_prefix<TAB>pattern[<TAB>column2_prefix]

A line without tabs is a bare pattern evaluated on --col.

For every pattern each mode (token, decode, raw) runs in its own CLI process.
The mode order rotates per pattern to spread thermal/turbo effects. Every
mode's row ids are compared with each other and with Person B's DuckDB ground
truth (data/truth/<dataset>/<name>.ids, generated by
scripts/verify/ground_truth.py). A pattern is "pass" only if every mode that
ran produced exactly the ground-truth row ids.
Only the standard library is used.
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import os
import platform
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODES = ["token", "decode", "raw"]
GROUND_TRUTH = "scripts/verify/ground_truth.py"
TRUTH_ROOT = "data/truth"
EXIT_UNAVAILABLE = 2


@dataclass(frozen=True)
class Pattern:
    name: str
    column: str
    pattern: str
    column2: str | None = None

    @property
    def truth_path(self) -> str:
        # Same rule as scripts/verify/common.py (Person B).
        dataset = os.path.basename(os.path.dirname(self.column)) or "default"
        return os.path.join(TRUTH_ROOT, dataset, self.name + ".ids")


def log(msg: str) -> None:
    print(msg, file=sys.stderr, flush=True)


def read_patterns(path: Path, default_col: str) -> list[Pattern]:
    pats: list[Pattern] = []
    for lineno, line in enumerate(path.read_bytes().decode("utf-8").split("\n"), 1):
        line = line.rstrip("\r")
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if "\t" not in line:
            pats.append(Pattern(f"pattern{lineno}", default_col, line))
            continue
        f = line.split("\t")
        if len(f) not in (3, 4) or not f[0] or not f[1]:
            raise SystemExit(f"{path}:{lineno}: expected name<TAB>column<TAB>pattern[<TAB>column2]")
        pats.append(Pattern(f[0], f[1], f[2], f[3] if len(f) == 4 else None))
    return pats


def find_cli(build_dir: Path) -> Path:
    for name in ("tokenlike.exe", "tokenlike"):
        p = build_dir / name
        if p.is_file():
            return p
    sys.exit(f"error: CLI not found in {build_dir}; build it first (see README)")


def git(*args: str) -> str | None:
    try:
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True,
                              check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def cpu_name() -> str:
    if sys.platform == "win32":
        try:
            import winreg
            key = winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE,
                                 r"HARDWARE\DESCRIPTION\System\CentralProcessor\0")
            return winreg.QueryValueEx(key, "ProcessorNameString")[0].strip()
        except OSError:
            pass
    try:
        for line in Path("/proc/cpuinfo").read_text().splitlines():
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor() or "unknown"


def cmake_cache(build_dir: Path) -> dict:
    out = {}
    try:
        for line in (build_dir / "CMakeCache.txt").read_text(errors="replace").splitlines():
            for key in ("CMAKE_CXX_COMPILER", "CMAKE_CXX_FLAGS", "CMAKE_BUILD_TYPE",
                        "CMAKE_CXX_FLAGS_RELEASE"):
                if line.startswith(key + ":"):
                    out[key] = line.split("=", 1)[1]
    except OSError:
        pass
    comp = out.get("CMAKE_CXX_COMPILER")
    if comp:
        try:
            out["compiler_version"] = subprocess.run(
                [comp, "--version"], capture_output=True, text=True).stdout.splitlines()[0]
        except (OSError, IndexError):
            pass
    return out


def sha256(path: Path | str) -> str | None:
    try:
        h = hashlib.sha256()
        with open(path, "rb") as f:
            for chunk in iter(lambda: f.read(1 << 20), b""):
                h.update(chunk)
        return h.hexdigest()
    except OSError:
        return None


def column_fingerprint(col: str) -> dict:
    fp: dict = {}
    for suffix in (".tok", ".off", ".raw", ".rawoff"):
        p = ROOT / (col + suffix)
        fp[suffix] = p.stat().st_size if p.exists() else None
    meta = ROOT / (col + ".meta.json")
    fp["meta_sha256"] = sha256(meta)
    return fp


def stale_binary(cli: Path) -> bool:
    newest = max((p.stat().st_mtime for d in ("src", "include") for p in (ROOT / d).rglob("*")
                  if p.is_file()), default=0)
    return cli.stat().st_mtime < newest


def run_cli(cli: Path, opts, mode: str, pat: Pattern, rowids: Path) -> dict:
    cmd = [str(cli), "--mode", mode, "--pattern", pat.pattern, "--col", pat.column,
           "--vocab", opts.vocab, "--runs", str(opts.runs), "--warmup", str(opts.warmup),
           "--rowids", str(rowids)]
    if pat.column2:
        cmd += ["--col2", pat.column2]
    if opts.pin_cpu >= 0:
        cmd += ["--pin-cpu", str(opts.pin_cpu)]
    try:
        p = subprocess.run(cmd, cwd=ROOT, capture_output=True, timeout=opts.timeout)
    except subprocess.TimeoutExpired:
        return {"status": "timeout"}
    stderr = p.stderr.decode("utf-8", "replace").strip()
    if p.returncode == EXIT_UNAVAILABLE:
        return {"status": "unavailable", "stderr": stderr}
    if p.returncode != 0:
        return {"status": "error", "exit": p.returncode, "stderr": stderr}
    lines = [l for l in p.stdout.decode("utf-8").splitlines() if l.strip()]
    if len(lines) != 1:
        return {"status": "error", "stderr": f"expected 1 JSON line, got {len(lines)}"}
    res = json.loads(lines[0])
    res["status"] = "ok"
    res["rowids_sha256"] = sha256(rowids)
    if res.get("loaders") != "official":
        res["status"] = "error"
        res["stderr"] = "CLI was built with test fixture loaders; rebuild with Person B's"
    return res


def ensure_truth(pattern_file: Path) -> str | None:
    """Generate/refresh DuckDB truth with Person B's tool. Returns an error or None."""
    if not (ROOT / GROUND_TRUTH).exists():
        return f"{GROUND_TRUTH} not found"
    p = subprocess.run([sys.executable, GROUND_TRUTH, str(pattern_file)], cwd=ROOT,
                       capture_output=True, text=True)
    return None if p.returncode == 0 else (p.stderr or p.stdout).strip()[-500:]


def verify(pat: Pattern, modes: dict) -> tuple[str, dict]:
    """Compare every successful mode's row ids with the DuckDB truth file."""
    ok = {m: r for m, r in modes.items() if r["status"] == "ok"}
    truth = ROOT / pat.truth_path
    if not ok:
        return "not_run", {"detail": "no mode ran"}
    if not truth.exists():
        return "not_run", {"detail": f"no ground truth at {pat.truth_path}"}
    want = sha256(truth)
    count = truth.stat().st_size // 4
    per_mode = {m: r["rowids_sha256"] == want for m, r in ok.items()}
    for m, good in per_mode.items():
        if not good:
            r = ok[m]
            r["verify_detail"] = f"expected {count} matches, got {r['matches']}"
    status = "pass" if all(per_mode.values()) else "fail"
    return status, {"truth": pat.truth_path, "truth_matches": count, "truth_sha256": want,
                    "modes": per_mode}


def fmt(x, spec=".2f") -> str:
    return "-" if x is None else format(x, spec)


def print_table(results: list[dict]) -> None:
    hdr = ["name", "pattern", "matches", "token ns/r", "decode ns/r", "raw ns/r", "dec/tok",
           "tok/row T", "tok/row D", "table KB", "dense KB", "verified"]
    rows = []
    for r in results:
        m = r["modes"]
        ns = {k: m.get(k, {}).get("ns_per_row") for k in MODES}
        speed = ns["decode"] / ns["token"] if ns["token"] and ns["decode"] else None
        anyok = next((v for v in m.values() if v.get("status") == "ok"), {})
        pat = r["pattern"] if len(r["pattern"]) <= 28 else r["pattern"][:25] + "..."
        rows.append([r["name"], pat, str(anyok.get("matches", "-")), fmt(ns["token"]),
                     fmt(ns["decode"]), fmt(ns["raw"]), fmt(speed) + ("x" if speed else ""),
                     fmt(m.get("token", {}).get("tokens_per_row")),
                     fmt(m.get("decode", {}).get("tokens_per_row")),
                     fmt(m.get("token", {}).get("table_kb"), ".1f"),
                     fmt(m.get("token", {}).get("dense_table_kb"), ".1f"),
                     r["verified"] + ("" if r["agree"] else " (modes disagree)")])
    widths = [max(len(h), *(len(row[i]) for row in rows)) for i, h in enumerate(hdr)]
    line = lambda cells: "  ".join(c.ljust(w) for c, w in zip(cells, widths))
    print(line(hdr))
    print(line(["-" * w for w in widths]))
    for row in rows:
        print(line(row))


def run_pattern(cli: Path, opts, modes: list[str], pat: Pattern, idx: int, rowdir: Path) -> dict:
    order = modes[idx % len(modes):] + modes[:idx % len(modes)]
    res: dict = {"name": pat.name, "pattern": pat.pattern, "column": pat.column,
                 "column2": pat.column2, "modes": {}}
    for mode in order:
        r = run_cli(cli, opts, mode, pat, rowdir / f"{pat.name}.{mode}.ids")
        res["modes"][mode] = r
        log(f"    {mode:6s} {r['status']}" + (
            f"  matches={r['matches']} ns/row={r['ns_per_row']:.3f}" if r["status"] == "ok"
            else f"  {r.get('stderr', '')[-200:]}"))
    ok = {m: r for m, r in res["modes"].items() if r["status"] == "ok"}
    res["agree"] = len({r["rowids_sha256"] for r in ok.values()}) <= 1
    res["modes_ok"] = sorted(ok)
    res["verified"], res["check"] = verify(pat, res["modes"])
    return res


def main() -> int:
    for stream in (sys.stdout, sys.stderr):  # Windows consoles default to cp1252
        stream.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("patterns", type=Path)
    ap.add_argument("--runs", type=int, default=5)
    ap.add_argument("--warmup", type=int, default=1)
    ap.add_argument("--out", type=Path, default=Path("results/final.json"))
    ap.add_argument("--col", default="data/clickbench/URL",
                    help="column for bare (untabbed) pattern lines")
    ap.add_argument("--vocab", default="data/vocab.bin")
    ap.add_argument("--build", type=Path, default=ROOT / "build")
    ap.add_argument("--modes", default=",".join(MODES))
    ap.add_argument("--rowids-dir", type=Path, default=Path("results/rowids"))
    ap.add_argument("--no-truth", action="store_true",
                    help="do not (re)generate DuckDB ground truth before running")
    ap.add_argument("--allow-dirty", action="store_true")
    ap.add_argument("--timeout", type=float, default=600)
    ap.add_argument("--pin-cpu", type=int, default=0,
                    help="logical CPU to pin every run to (-1 = no pinning)")
    args = ap.parse_args()

    if args.runs < 5:
        log(f"warning: --runs {args.runs} < 5; not acceptable for final results")
    modes = [m for m in args.modes.split(",") if m]
    cli = find_cli(args.build)
    patterns = read_patterns(args.patterns, args.col)

    status = git("status", "--porcelain", "--untracked-files=no")
    dirty = bool(status) if status is not None else None
    if dirty and not args.allow_dirty:
        sys.exit("error: working tree has uncommitted changes; commit or pass --allow-dirty")
    if stale_binary(cli):
        log("warning: CLI binary is older than sources; rebuild before final measurements")

    truth_error = None
    if not args.no_truth:
        log("generating / refreshing DuckDB ground truth ...")
        truth_error = ensure_truth(args.patterns)
        if truth_error:
            log(f"warning: ground truth generation failed: {truth_error}")

    columns = sorted({c for p in patterns for c in (p.column, p.column2) if c})
    meta = {
        "timestamp_utc": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "git_commit": git("rev-parse", "HEAD"),
        "git_branch": git("rev-parse", "--abbrev-ref", "HEAD"),
        "git_dirty": dirty,
        "host": platform.node(),
        "os": platform.platform(),
        "cpu": cpu_name(),
        "logical_cpus": os.cpu_count(),
        "python": platform.python_version(),
        "build": cmake_cache(args.build),
        "cli": str(cli.relative_to(ROOT)) if cli.is_relative_to(ROOT) else str(cli),
        "patterns_file": str(args.patterns),
        "patterns_sha256": sha256(args.patterns),
        "runs": args.runs, "warmup": args.warmup, "pin_cpu": args.pin_cpu,
        "vocab": {"path": args.vocab, "sha256": sha256(ROOT / args.vocab)},
        "columns": {c: column_fingerprint(c) for c in columns},
        "ground_truth": "skipped" if args.no_truth else (truth_error or "ok"),
    }

    rowdir = ROOT / args.rowids_dir
    rowdir.mkdir(parents=True, exist_ok=True)
    results = []
    for i, pat in enumerate(patterns):
        log(f"[{i + 1}/{len(patterns)}] {pat.name}: {pat.pattern!r}")
        results.append(run_pattern(cli, args, modes, pat, i, rowdir))

    out = ROOT / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps({"meta": meta, "results": results}, indent=2, ensure_ascii=False)
                   + "\n", encoding="utf-8")

    print_table(results)
    summary = {s: sum(r["verified"] == s for r in results) for s in ("pass", "fail", "not_run")}
    print(f"\nverified vs DuckDB: {summary}")
    print(f"written {args.out}  (commit {str(meta['git_commit'])[:10]}, "
          f"dirty={dirty}, cpu={meta['cpu']})")
    bad = [r["name"] for r in results if not r["agree"] or r["verified"] == "fail"]
    if bad:
        print(f"FAILED patterns: {bad}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
